function interpolate(template: string, params: TranslationParams = {}) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const value = params[key];
    return value == null ? "" : String(value);
  });
}

function formatEntry(entry: TranslationEntry, params?: TranslationParams) {
  if (typeof entry === "function") {
    return entry(params ?? {});
  }
  return interpolate(entry, params);
}

export function parseLanguage(value: string | null): Language {
  return value === "en" || value === "zh-CN" ? value : "zh-CN";
}

export function createTranslator(language: Language): Translator {
  return (key, params) => {
    const entry = messages[language][key] ?? messages.en[key];
    if (!entry) return key;
    return formatEntry(entry, params);
  };
}

type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: Translator;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider(props: { value: I18nContextValue; children: ReactNode }) {
  return <I18nContext.Provider value={props.value}>{props.children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used within an I18nProvider.");
  }
  return value;
}
